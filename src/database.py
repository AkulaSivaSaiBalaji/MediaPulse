"""MediaPulse Database Connection and Session Management Module.

Provides SQLAlchemy engine creation, session factory management, connection health
checks, schema initialization, and transactional context managers.
"""

from contextlib import contextmanager
import logging
from pathlib import Path
from typing import Any, Dict, Generator, Optional
from sqlalchemy import create_engine, text
from sqlalchemy.engine import Engine
from sqlalchemy.exc import OperationalError, SQLAlchemyError
from sqlalchemy.orm import Session, declarative_base, sessionmaker

from src import config

logger = logging.getLogger("mediapulse.database")

# Declarative Base for ORM models
Base = declarative_base()


def get_engine(
    db_url: Optional[str] = None,
    echo: bool = False,
    pool_size: int = 5,
    max_overflow: int = 10,
    pool_recycle: int = 3600,
) -> Engine:
    """Create and configure a SQLAlchemy Engine.

    Args:
        db_url: Optional explicit database URL. If omitted, uses config.get_db_connection_url().
        echo: If True, logs SQL statements generated by SQLAlchemy.
        pool_size: Connection pool size.
        max_overflow: Max number of connections to allow beyond pool_size.
        pool_recycle: Seconds after which to recycle connections.

    Returns:
        Configured SQLAlchemy Engine.
    """
    url = db_url or config.get_db_connection_url()
    safe_url = config.get_db_connection_url(mask_password=True) if db_url is None else "custom_url"
    logger.info("Initializing SQLAlchemy Engine for: %s", safe_url)

    # SQLite does not support pool_size and max_overflow
    if url.startswith("sqlite"):
        return create_engine(url, echo=echo)

    return create_engine(
        url,
        echo=echo,
        pool_size=pool_size,
        max_overflow=max_overflow,
        pool_recycle=pool_recycle,
        pool_pre_ping=True,
    )


def test_connection(engine: Optional[Engine] = None) -> Dict[str, Any]:
    """Verify database connectivity and retrieve server version info.

    Args:
        engine: Optional SQLAlchemy Engine. If omitted, builds default engine.

    Returns:
        Dictionary containing connection status, database version, and error details if any.
    """
    eng = engine or get_engine()
    safe_url = config.get_db_connection_url(mask_password=True)

    try:
        with eng.connect() as conn:
            if eng.name == "sqlite":
                result = conn.execute(text("SELECT sqlite_version();")).fetchone()
            else:
                result = conn.execute(text("SELECT VERSION();")).fetchone()
            version = result[0] if result else "Unknown"
            logger.info("Successfully connected to database. Version: %s", version)
            return {
                "connected": True,
                "version": version,
                "url": safe_url,
                "error": None,
            }
    except OperationalError as e:
        logger.error("OperationalError connecting to database: %s", e)
        return {
            "connected": False,
            "version": None,
            "url": safe_url,
            "error": str(e),
        }
    except Exception as e:
        logger.error("Unexpected error connecting to database: %s", e)
        return {
            "connected": False,
            "version": None,
            "url": safe_url,
            "error": str(e),
        }


def get_session_factory(engine: Optional[Engine] = None) -> sessionmaker:
    """Create a configured sessionmaker bound to the given engine."""
    eng = engine or get_engine()
    return sessionmaker(autocommit=False, autoflush=False, bind=eng)


@contextmanager
def get_db_session(engine: Optional[Engine] = None) -> Generator[Session, None, None]:
    """Provide a transactional scope around a series of operations with automatic rollback.

    Yields:
        Active SQLAlchemy Session.
    """
    session_factory = get_session_factory(engine)
    session: Session = session_factory()
    try:
        yield session
        session.commit()
    except Exception as e:
        session.rollback()
        logger.error("Transaction rolled back due to error: %s", e)
        raise
    finally:
        session.close()


def create_database_if_not_exists(db_name: Optional[str] = None) -> None:
    """Create target database on server if it does not already exist."""
    name = db_name or config.DB_NAME
    server_url = config.get_db_connection_url(include_db=False)
    # Only applicable for MySQL / PostgreSQL engines
    if server_url.startswith("sqlite"):
        return
    server_engine = create_engine(server_url)
    with server_engine.connect() as conn:
        conn.execute(text(f"CREATE DATABASE IF NOT EXISTS `{name}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"))
        conn.commit()
    logger.info("Database '%s' verified/created on server", name)


def execute_sql_file(file_path: Path, engine: Optional[Engine] = None) -> None:
    """Execute raw SQL statements from a file (e.g., schema.sql) in order.

    Args:
        file_path: Path to the .sql file.
        engine: Optional SQLAlchemy Engine.
    """
    if not file_path.exists():
        raise FileNotFoundError(f"SQL file not found at: {file_path}")

    eng = engine or get_engine()
    sql_text = file_path.read_text(encoding="utf-8")

    # Remove single-line comments prior to splitting by semicolon
    lines = [line for line in sql_text.splitlines() if not line.strip().startswith("--")]
    clean_sql = "\n".join(lines)

    # Split statements by semicolon, ignoring empty blocks
    statements = [stmt.strip() for stmt in clean_sql.split(";") if stmt.strip()]

    with eng.connect() as conn:
        with conn.begin():
            for stmt in statements:
                if stmt:
                    conn.execute(text(stmt))

    logger.info("Executed %d SQL statements from %s", len(statements), file_path.name)
